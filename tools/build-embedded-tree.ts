/**
 * Generates `emet/src/embedded-tree.generated.ts`: the install tree (the
 * `commands`, `agents`, `emet/reference`, hook, Codex skill and plugin
 * manifest files) inlined as strings, so a compiled binary, or the copied
 * `emet/` source tree, needs no repository tree.
 *
 * `bun tools/build-embedded-tree.ts` writes the module; `--check` exits 1 and
 * names the stale tree files when the committed module differs from what the
 * generator would write.
 */
import { spawnSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const repoRoot = path.join(import.meta.dir, "..");

/** The generated module, relative to the repository root. */
export const GENERATED_PATH = "emet/src/embedded-tree.generated.ts";

const TREE_DIRECTORIES: readonly string[] = ["commands", "agents", "emet/reference"];

const TREE_FILES: readonly string[] = [
  "hooks/hooks.json",
  "codex/hooks.json",
  ".codex-plugin/plugin.json",
  ".claude-plugin/plugin.json",
];

/** Lists the files under `directory` as sorted root-relative paths, descending when `deep`. */
function listFiles(root: string, directory: string, deep: boolean): string[] {
  const absolute = path.join(root, directory);
  if (!existsSync(absolute)) return [];
  return readdirSync(absolute, { withFileTypes: true })
    .flatMap((entry) => {
      const relative = `${directory}/${entry.name}`;
      if (entry.isDirectory()) return deep ? listFiles(root, relative, deep) : [];
      return [relative];
    })
    .toSorted();
}

/** The sorted repo-relative paths of the install tree that exist under `root`. */
export function listTreePaths(root: string = repoRoot): string[] {
  const flat = TREE_DIRECTORIES.flatMap((directory) =>
    listFiles(root, directory, false).filter((file) => file.endsWith(".md")),
  );
  const files = TREE_FILES.filter((file) => existsSync(path.join(root, file)));
  return [...flat, ...files, ...listFiles(root, "codex/skills", true)].toSorted();
}

/** One tree file as the JSON string literal the module holds. */
function literal(root: string, file: string): string {
  return JSON.stringify(readFileSync(path.join(root, file), "utf8"));
}

/** Renders the generated module for the tree under `root`. */
export function renderModule(root: string = repoRoot): string {
  const entries = listTreePaths(root).map(
    (file) => `  ${JSON.stringify(file)}: ${literal(root, file)},`,
  );
  return [
    "/** Generated by `bun tools/build-embedded-tree.ts`; do not edit. */",
    "export const EMBEDDED_TREE: Readonly<Record<string, string>> = {",
    ...entries,
    "};",
    "",
  ].join("\n");
}

/** Loads the committed module's tree, whatever formatting it carries; empty when absent. */
async function committedTree(root: string): Promise<ReadonlyMap<string, string>> {
  const generatedFile = path.join(root, GENERATED_PATH);
  if (!existsSync(generatedFile)) return new Map();
  const loaded: unknown = await import(`${generatedFile}?stamp=${Bun.nanoseconds()}`);
  const tree: unknown = Reflect.get(Object(loaded), "EMBEDDED_TREE");
  const entries = typeof tree === "object" && tree !== null ? Object.entries(tree) : [];
  return new Map(entries.map(([file, text]) => [file, String(text)]));
}

/**
 * The tree files that make the committed module stale: added, removed or edited since it was
 * generated, compared by content so formatting of the module does not matter.
 */
export async function findStaleFiles(root: string = repoRoot): Promise<string[]> {
  const recorded = await committedTree(root);
  const paths = listTreePaths(root);
  const changed = paths.filter(
    (file) => recorded.get(file) !== readFileSync(path.join(root, file), "utf8"),
  );
  const removed = [...recorded.keys()].filter((file) => !paths.includes(file));
  return [...changed, ...removed];
}

/** Writes the generated module under `root` and returns how many files it embeds. */
export function writeModule(root: string = repoRoot): number {
  writeFileSync(path.join(root, GENERATED_PATH), renderModule(root));
  return listTreePaths(root).length;
}

/** Formats `file` in place with the repo's formatter so the written module passes `format:check`. */
function formatFile(file: string): void {
  const result = spawnSync("bun", ["x", "oxfmt", file], { cwd: repoRoot, encoding: "utf8" });
  if (result.status !== 0) throw new Error(`oxfmt failed on ${file}: ${result.stderr}`);
}

/** Writes the generated module under `root`, formats it and returns how many files it embeds. */
export function regenerateModule(
  root: string = repoRoot,
  format: (file: string) => void = formatFile,
): number {
  const count = writeModule(root);
  format(path.join(root, GENERATED_PATH));
  return count;
}

/**
 * Entry point: writes the module, or with `--check` reports stale files.
 * @param argv The command-line arguments.
 * @param root The repository root.
 * @param log Receives the success line.
 * @param error Receives the stale-files report.
 * @returns The process exit code: 1 when `--check` finds stale files, else 0.
 */
export async function main(
  argv: readonly string[],
  root: string = repoRoot,
  log: (message: string) => void = console.log,
  error: (message: string) => void = console.error,
): Promise<number> {
  if (argv.includes("--check")) {
    const stale = await findStaleFiles(root);
    if (stale.length > 0) {
      error(`stale embedded tree (run bun tools/build-embedded-tree.ts):\n${stale.join("\n")}`);
      return 1;
    }
    return 0;
  }
  log(`embedded ${regenerateModule(root)} install tree files`);
  return 0;
}

if (import.meta.main) {
  process.exitCode = await main(process.argv.slice(2));
}
